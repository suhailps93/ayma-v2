def _delete_subcollections(db, uid: str) -> None:
    import schema

    user_ref = db.collection("users").document(uid)
    for sub in schema.ACCOUNT_SUBCOLLECTIONS + ("practice_sessions",):
        for snap in user_ref.collection(sub).stream():
            # one nested case: wiki_pages/{id}/versions
            for vsnap in snap.reference.collection("versions").stream():
                vsnap.reference.delete()
            snap.reference.delete()
    user_ref.delete()


def reset_accounts(db, personas: dict) -> None:
    from firebase_admin import auth as fb_auth
    from pair_key import sorted_pair_key
    from dm_schema import thread_id

    uids = [p["uid"] for p in personas["personas"]]
    founder_uid = _founder_uid(db)
    _log("[reset] deleting account data, matches, dm_threads...")
    for uid in uids:
        _delete_subcollections(db, uid)
        try:
            fb_auth.delete_user(uid)
        except Exception as exc:  # noqa: BLE001
            _log(f"[reset] auth delete {uid}: {exc}")
    # cross-account docs
    pair_targets = uids + ([founder_uid] if founder_uid else [])
    for a in uids:
        for b in pair_targets:
            if a == b:
                continue
            db.collection("matches").document(sorted_pair_key(a, b)).delete()
            tref = db.collection("dm_threads").document(thread_id(a, b))
            for m in tref.collection("messages").stream():
                m.reference.delete()
            tref.delete()
    _log("[reset] done.")


