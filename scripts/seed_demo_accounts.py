async def build_photos(db, persona: dict, *, regen: bool) -> None:
    import gemini
    import photo_ops
    import photo_pipeline
    import schema
    from firebase_admin import storage
    from config import CONFIG

    uid = persona["uid"]
    prof = schema.profile_doc(db, uid).get().to_dict() or {}
    if len(prof.get("photos") or []) >= 3 and not regen:
        _log(f"[photos] {uid}: {len(prof['photos'])} photos present, skipping gen")
        return

    bucket = storage.bucket(CONFIG.storage_bucket)
    prompts = persona["image_prompts"]
    order = [("face", prompts["face"]), ("body", prompts["body"]),
             ("candid", prompts["candid"])]
    ref_image = None
    media_ids: list[str] = []
    for kind, prompt in order:
        try:
            img, mime = await gemini.generate_image(prompt, image=ref_image, uid=None)
        except Exception as exc:  # noqa: BLE001
            _log(f"[photos] {uid}: generate {kind} FAILED: {exc}")
            continue
        if ref_image is None:
            ref_image = (img, mime)  # anchor identity for later shots
        ext = "png" if "png" in (mime or "").lower() else "jpg"
        path = f"uploads/{uid}/seed_{kind}.{ext}"
        blob = bucket.blob(path)
        blob.metadata = {"firebaseStorageDownloadTokens": str(uuid.uuid4())}
        blob.upload_from_string(img, content_type=mime or "image/png")
        try:
            result = await photo_pipeline.process(db, uid, path, "profile")
        except Exception as exc:  # noqa: BLE001
            _log(f"[photos] {uid}: pipeline {kind} FAILED: {exc}")
            continue
        mid = result.get("media_id")
        status = result.get("moderation_status")
        attrs = result.get("attributes") or {}
        _log(f"[photos] {uid}: {kind} -> media={mid} status={status} "
             f"shot={attrs.get('shot_type')} face={attrs.get('usable_for_face')} "
             f"body={attrs.get('usable_for_body')}")
        if mid and status == "approved":
            media_ids.append(mid)
    if media_ids:
        photo_ops.add_photos(db, uid, media_ids)
        photo_ops.set_primary(db, uid, media_ids[0])
        _log(f"[photos] {uid}: grid set, {len(media_ids)} photos, primary={media_ids[0]}")


