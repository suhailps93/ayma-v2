def ensure_auth_user(persona: dict) -> None:
    from firebase_admin import auth as fb_auth

    uid, email, name = persona["uid"], persona["email"], persona["name"]
    try:
        fb_auth.get_user(uid)
        fb_auth.update_user(
            uid, email=email, password=PASSWORD, display_name=name,
            email_verified=False,
        )
        _log(f"[auth] updated {email} (uid={uid})")
    except fb_auth.UserNotFoundError:
        fb_auth.create_user(
            uid=uid, email=email, password=PASSWORD, display_name=name,
            email_verified=False,
        )
        _log(f"[auth] created {email} (uid={uid})")


def _qz_map(personas: dict, key: str) -> dict:
    merged = dict(personas["qz_shared_good"])
    merged.update(personas["qz_overrides"].get(key, {}))
    return merged


def write_profile_and_questionnaire(db, persona: dict, qz: dict, location: str) -> None:
    import schema

    uid = persona["uid"]
    # partner age range is also a (scored, completeness-tracked) questionnaire
    # node pair, not only a profile mirror.
    qz = dict(qz)
    qz["partner_age_min"] = persona["partner_age_min"]
    qz["partner_age_max"] = persona["partner_age_max"]
    profile = {
        "name": persona["name"],
        "first_name": persona["first_name"],
        "last_name": persona["last_name"],
        "gender": persona["gender"],
        "interested_in": persona["interested_in"],
        "birthdate": persona["birthdate"],
        "location": location,
        "headline": persona["headline"],
        "relationship_intent": qz["relationship_intent"],
        "qz_partner_age_min": persona["partner_age_min"],
        "qz_partner_age_max": persona["partner_age_max"],
        "partner_age_min": persona["partner_age_min"],
        "partner_age_max": persona["partner_age_max"],
        "distance_pref": "50",
        "ai_avatar_enabled": True,
        "paused": False,
        "onboarding_complete": True,
    }
    # qz_* mirrors (profile/main) — matching reads these first.
    for node_id, value in qz.items():
        profile[f"qz_{node_id}"] = value
    schema.profile_doc(db, uid).set(profile, merge=True)

    # questionnaire/{node_id} answers
    qcol = db.collection("users").document(uid).collection("questionnaire")
    for node_id, value in qz.items():
        qcol.document(node_id).set(
            {
                "node_id": node_id,
                "value": value,
                "source": "stated",
                "confidence": "high",
                "updated_at": _now(),
            },
            merge=True,
        )
    _log(f"[profile] wrote profile/main + {len(qz)} questionnaire answers for {uid}")


