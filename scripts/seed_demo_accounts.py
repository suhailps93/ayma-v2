def _founder_uid(db):
    from firebase_admin import auth as fb_auth

    try:
        return fb_auth.get_user_by_email(FOUNDER_EMAIL).uid
    except Exception:  # noqa: BLE001
        return None


async def persist_match(db, a: str, b: str) -> float | None:
    import matching_skill
    from pair_key import sorted_pair_key

    try:
        res = await matching_skill.score_pair(db, a, b)
    except Exception as exc:  # noqa: BLE001
        _log(f"[match] {a} x {b}: FAILED: {exc}")
        return None
    score = res.get("score")
    db.collection("matches").document(sorted_pair_key(a, b)).set(
        {
            "uids": sorted([a, b]),
            "score": score,
            "user_explanation": res.get("user_explanation") or {},
            "ai_explanation": res.get("ai_explanation") or "",
            "trust_flags": res.get("trust_flags") or {},
            "status": "scored",
            "scored_at": _now(),
            "updated_at": _now(),
        },
        merge=True,
    )
    _log(f"[match] {a} x {b}: score={score}")
    return score


def drive_dm(db, a_persona: dict, b_persona: dict, quality: str, *, regen: bool) -> None:
    import dm_ops
    from dm_schema import thread_id

    a, b = a_persona["uid"], b_persona["uid"]
    tref = db.collection("dm_threads").document(thread_id(a, b))
    has_msgs = any(True for _ in tref.collection("messages").limit(1).stream())
    if has_msgs and not regen:
        _log(f"[dm] {a} x {b}: thread present, skipping")
        return
    if has_msgs:  # regen: clear
        for m in tref.collection("messages").stream():
            m.reference.delete()
    tmpl = (
        _prompt("dm_thread.md")
        .replace("{a_name}", a_persona["first_name"])
        .replace("{a_brief}", a_persona["brief"])
        .replace("{b_name}", b_persona["first_name"])
        .replace("{b_brief}", b_persona["brief"])
        .replace("{match_quality}", quality)
    )
    msgs = _gen_json(tmpl)
    sent = 0
    for m in msgs:
        sender = a if m["sender"] == "a" else b
        other = b if m["sender"] == "a" else a
        try:
            dm_ops.post_message(db, sender, other, "text", str(m["text"]))
            sent += 1
        except Exception as exc:  # noqa: BLE001
            _log(f"[dm] {a} x {b}: post FAILED: {exc}")
            break
    _log(f"[dm] {a_persona['first_name']} x {b_persona['first_name']} ({quality}): "
         f"{sent} messages")


async def drive_avatar_chat(db, viewer_uid: str, target_persona: dict, *, regen: bool) -> None:
    import practice_core

    target = target_persona["uid"]
    sid = f"seed-avatar-{target}"
    sref = (
        db.collection("users").document(viewer_uid)
        .collection("practice_sessions").document(sid)
    )
    if sref.get().exists and not regen:
        _log(f"[avatarchat] {viewer_uid} -> {target}: session present, skipping")
        return
    ctx = practice_core.build_persona_context(db, viewer_uid, target)
    if ctx is None:
        _log(f"[avatarchat] {viewer_uid} -> {target}: no persona context")
        return
    openers = [
        f"Hey {target_persona['first_name']}! Your profile caught my eye — "
        "what's a perfect weekend look like for you?",
        "Love that. What kind of music or films are you into lately?",
        "Nice — what are you hoping to find in someone?",
    ]
    turns: list[dict] = []
    for msg in openers:
        try:
            # prior history + the new message, as the real practice chat does
            reply = await practice_core.persona_reply(
                ctx, turns, msg, uid=viewer_uid, session_id=sid
            )
        except Exception as exc:  # noqa: BLE001
            _log(f"[avatarchat] {viewer_uid} -> {target}: reply FAILED: {exc}")
            return
        turns.append({"role": "user", "text": msg})
        turns.append({"role": "assistant", "text": reply})
    sref.set(
        {
            "target_uid": target,
            "created_at": datetime.now(timezone.utc).timestamp(),
            "ended_at": datetime.now(timezone.utc).timestamp(),
            "turns": turns,
        }
    )
    _log(f"[avatarchat] {viewer_uid} -> {target_persona['first_name']}: "
         f"{len(turns)} turns; last reply: {turns[-1]['text'][:80]!r}")


# ---------------------------------------------------------------------------
# orchestration
# ---------------------------------------------------------------------------
async def run(args) -> int:
    import firebase_admin

    try:
        firebase_admin.initialize_app()
    except ValueError:
        pass
    from db import get_db

    db = get_db()
    personas = _load_personas()
    location = personas["location"]
    plist = personas["personas"]
    by_key = {p["key"]: p for p in plist}

    if args.reset:
        reset_accounts(db, personas)

    _log("\n=== PHASE 1: accounts, profiles, taste, story, conversation ===")
    for p in plist:
        qz = _qz_map(personas, p["key"])
        ensure_auth_user(p)
        record_consent(db, p["uid"])  # before photos so face embeddings persist
        write_profile_and_questionnaire(db, p, qz, location)
        write_taste(db, p)
        if not args.no_llm:
            write_story(db, p, regen=args.reset)
            write_conversation(db, p, regen=args.reset)

    _log("\n=== PHASE 2: photos + appearance ===")
    if not args.no_images:
        for p in plist:
            await build_photos(db, p, regen=args.reset)
            await build_appearance(db, p["uid"])

    _log("\n=== PHASE 3: completeness, avatar, credits ===")
    for p in plist:
        await recompute_completeness(db, p["uid"])
        await build_avatar_snapshot(db, p["uid"])
        grant_credits(p["uid"])

    _log("\n=== PHASE 4: matches ===")
    t1, t2, t3 = by_key["test1"]["uid"], by_key["test2"]["uid"], by_key["test3"]["uid"]
    founder = _founder_uid(db)
    await persist_match(db, t1, t2)
    await persist_match(db, t1, t3)
    if founder:
        await persist_match(db, founder, t2)
        await persist_match(db, founder, t3)
        _log(f"[match] founder uid = {founder}")

    if not args.no_llm:
        _log("\n=== PHASE 5: DMs ===")
        drive_dm(db, by_key["test1"], by_key["test2"], "strong", regen=args.reset)
        drive_dm(db, by_key["test1"], by_key["test3"], "mismatched", regen=args.reset)

        _log("\n=== PHASE 6: avatar chats ===")
        await drive_avatar_chat(db, t1, by_key["test2"], regen=args.reset)
        await drive_avatar_chat(db, t1, by_key["test3"], regen=args.reset)

    _log("\n=== DONE ===")
    return 0


def main() -> int:
    ap = argparse.ArgumentParser(description="Seed the 3 Ayma demo accounts.")
    ap.add_argument("--reset", action="store_true",
                    help="wipe the 3 accounts' data + auth, then rebuild")
    ap.add_argument("--no-images", action="store_true",
                    help="skip (slow) Gemini image generation")
    ap.add_argument("--no-llm", action="store_true",
                    help="skip Gemini story/conversation/DM/avatar generation")
    args = ap.parse_args()
    return asyncio.run(run(args))


if __name__ == "__main__":
    raise SystemExit(main())
