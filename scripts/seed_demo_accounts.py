def write_story(db, persona: dict, *, regen: bool) -> None:
    uid = persona["uid"]
    wiki = db.collection("users").document(uid).collection("wiki_pages")
    existing = {s.id for s in wiki.stream()}
    story_slugs = existing - {"taste"}
    if story_slugs and not regen:
        _log(f"[story] {uid}: {len(story_slugs)} pages present, skipping gen")
        return
    pages = _gen_json(_fmt(_prompt("story_pages.md"), persona))
    for page in pages:
        pid = str(page["page_id"]).strip()
        wiki.document(pid).set(
            {
                "ai_body": page["ai_body"],
                "visibility": "public",
                "page_type": page["page_type"],
                "title": page["title"],
                "created_at": _now(),
                "updated_at": _now(),
                "ai_body_updated_at": _now(),
            },
            merge=True,
        )
    _log(f"[story] {uid}: wrote {len(pages)} story pages")


def write_conversation(db, persona: dict, *, regen: bool) -> None:
    import post_turn
    import transcript

    uid = persona["uid"]
    raw_ref = (
        db.collection("users").document(uid)
        .collection("raw_turns").document(ONBOARDING_SESSION)
    )
    chat_col = db.collection("users").document(uid).collection("chat_messages")
    if raw_ref.get().exists and not regen:
        _log(f"[chat] {uid}: onboarding conversation present, skipping gen")
        return
    turns_raw = _gen_json(_fmt(_prompt("ayma_conversation.md"), persona))
    turns = [
        transcript.Turn(role=("user" if t["role"] == "user" else "ayma"),
                        text=str(t["text"]))
        for t in turns_raw
    ]
    post_turn.persist_raw_turns(db, uid, ONBOARDING_SESSION, turns)
    # deterministic chat_messages (idempotent): clear old seed rows, rewrite
    for old in chat_col.where("client_msg_id", ">=", "seed-").where(
        "client_msg_id", "<", "seed-~"
    ).stream():
        old.reference.delete()
    for i, t in enumerate(turns_raw):
        cid = f"seed-{i:04d}"
        chat_col.document(cid).set(
            {
                "role": "user" if t["role"] == "user" else "ayma",
                "text": str(t["text"]),
                "image_path": "",
                "image_url": "",
                "created_at": _now(),
                "client_msg_id": cid,
            }
        )
    _log(f"[chat] {uid}: wrote {len(turns_raw)} chat turns + raw_turns")


