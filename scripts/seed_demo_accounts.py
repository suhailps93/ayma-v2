def _log(msg: str) -> None:
    print(msg, flush=True)


def _now():
    from firebase_admin import firestore

    return firestore.SERVER_TIMESTAMP


def _load_personas() -> dict:
    return json.loads(_DATA.read_text(encoding="utf-8"))


def _prompt(name: str) -> str:
    return (_PROMPTS / name).read_text(encoding="utf-8")


def _gen_json(prompt: str):
    """One Vertex-Gemini call that must return a JSON array/object."""
    from config import CONFIG
    from google import genai
    from google.genai import types

    client = genai.Client(
        vertexai=True,
        project=CONFIG.project_id or "ayma-ai",
        location=CONFIG.gemini_location,
    )
    resp = client.models.generate_content(
        model=CONFIG.gemini_model,
        contents=prompt,
        config=types.GenerateContentConfig(response_mime_type="application/json"),
    )
    text = (resp.text or "").strip()
    if text.startswith("```"):
        text = text.split("```", 2)[1]
        if text.startswith("json"):
            text = text[4:]
        text = text.strip()
    return json.loads(text)


def _fmt(template: str, persona: dict) -> str:
    t = persona["taste"]
    return (
        template.replace("{brief}", persona["brief"])
        .replace("{music}", ", ".join(t["music"]))
        .replace("{film}", ", ".join(t["film"]))
        .replace("{food}", ", ".join(t["food"]))
    )


