#!/usr/bin/env python3
"""Seed the three hackathon demo/judge accounts (docs/DEMO_ACCOUNTS.md).

Creates/updates test1/test2/test3 as COMPLETE, lived-in demo profiles against
the real ``ayma-ai`` Firestore + Firebase Auth + Storage, using the app's own
production code paths. Idempotent: safe to re-run (deterministic uids + upserts);
``--reset`` wipes the three accounts' data and rebuilds from scratch.

What it builds per persona (facts in ``scripts/demo_seed/personas.json``,
prompt templates in ``prompts/demo_seed/*.md`` — never inline, per AGENTS.md):
  * Firebase Auth user (custom uid, password, display name)
  * profile/main (name, birthdate, gender, interested_in, location, partner
    prefs, every qz_* mirror, ai_avatar_enabled)
  * questionnaire/{node_id} answers (drives matching + completeness)
  * public Taste page + taste nodes (Qloo) via the real questionnaire pipeline
  * Story (wiki_pages) — generated by Gemini from the persona brief
  * A multi-turn Ayma conversation (chat_messages + raw_turns) — Gemini
  * AI photos (face + full-body + candid) via Gemini image gen, run through the
    real photo pipeline (moderation + attributes + grid), then an Appearance
    report; biometric consent recorded (admin_seed)
  * completeness recompute + persona-snapshot AI avatar
  * a free credit top-up
Then, across accounts:
  * matches/{pair} docs for test1xtest2 (good) and test1xtest3 (bad), plus the
    founder, via the real score_pair
  * real DM threads (test1<->test2 strong, test1<->test3 mismatched) — turns
    generated by Gemini, posted through dm_ops
  * real human<->AI-avatar chats (test1 chats test2 & test3 avatars) via
    practice_core.persona_reply

Credentials: Application Default Credentials (``gcloud auth application-default
login`` locally; the Cloud Run identity when deployed). No secrets are read or
written by this script. Run it from the repo root:

    python3 scripts/seed_demo_accounts.py            # build / upsert
    python3 scripts/seed_demo_accounts.py --reset    # wipe + rebuild
    python3 scripts/seed_demo_accounts.py --no-images # skip (slow) image gen
    python3 scripts/seed_demo_accounts.py --no-llm    # skip Gemini content gen

Local runs force the Vertex-Gemini transport (``FLAG_LLM_ROUTE_*=vertex``,
``GOOGLE_CLOUD_PROJECT=ayma-ai``) because the deployed Meta/Inference routing
needs secrets this script doesn't carry. This only affects THIS process; it
changes no committed default and no deployed config.
"""

